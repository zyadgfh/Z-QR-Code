export function money(lang: Lang, n: number) {
  return lang === 'ar' ? `${n} ج.م` : `EGP ${n}`;
}

export function fmtDate(lang: Lang, ts: number | null) {
  if (!ts) return '—';
  return new Date(ts).toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-GB', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

export function timeAgo(lang: Lang, ts: number, now = Date.now()) {
  const mins = Math.max(1, Math.floor((now - ts) / 60000));
  if (mins < 60) return lang === 'ar' ? `منذ ${mins} د` : `${mins}m ago`;
  const h = Math.floor(mins / 60);
  return lang === 'ar' ? `منذ ${h} س` : `${h}h ago`;
}
