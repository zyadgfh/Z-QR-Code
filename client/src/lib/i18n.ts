export type DashDict = typeof dash.ar;
export type DashKey = keyof DashDict;

export function dashT(lang: Lang) {
  return (key: DashKey, vars?: Record<string, string | number>) => {
    let s: string = dash[lang][key] ?? dash.ar[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

